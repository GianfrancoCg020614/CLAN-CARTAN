alter table public.cc_portal_stream_orders add column order_no bigint generated by default as identity (start with 100000);
alter table public.cc_portal_stream_orders add column order_code text generated always as ('ORD-'||order_no::text) stored;
create unique index cc_stream_order_no_unique on public.cc_portal_stream_orders(order_no);
create unique index cc_stream_order_code_unique on public.cc_portal_stream_orders(order_code);

create table cc_internal.sb_mail_connections(
 id uuid primary key default gen_random_uuid(),owner_id uuid not null references auth.users(id),provider text not null check(provider in ('google','microsoft')),
 provider_subject text not null,email_address text not null,status text not null check(status in ('CONNECTED','REAUTH_REQUIRED','DISCONNECTED')),
 token_secret_id uuid references vault.secrets(id),created_at timestamptz not null default now(),updated_at timestamptz not null default now(),
 unique(owner_id,provider,provider_subject)
);
create index sb_mail_owner on cc_internal.sb_mail_connections(owner_id);
create table cc_internal.sb_mail_oauth_states(
 state_hash text primary key,owner_id uuid not null references auth.users(id),provider text not null check(provider in ('google','microsoft')),
 verifier_secret_id uuid not null references vault.secrets(id),expires_at timestamptz not null,created_at timestamptz not null default now()
);
create table cc_internal.sb_delivery_accounts(
 account_id uuid primary key references public.sb_oper_accounts(id),product_id uuid not null references public.cc_portal_stream_products(id),
 method text not null check(method in ('AUTOMATIC','AUTHENTICATOR','MANUAL','DIRECT')),
 connection_id uuid references cc_internal.sb_mail_connections(id),authorized_sender text,commercial_authorized boolean not null check(commercial_authorized),
 revision bigint not null default 1,updated_at timestamptz not null default now(),
 check(method<>'AUTOMATIC' or connection_id is not null and authorized_sender is not null)
);
create table cc_internal.sb_order_delivery(
 order_id uuid primary key references public.cc_portal_stream_orders(id),account_id uuid references public.sb_oper_accounts(id),
 duration_days integer not null check(duration_days between 1 and 3650),valid_from timestamptz,valid_until timestamptz,
 lifecycle text not null default 'PENDING' check(lifecycle in ('PENDING','ACTIVE','SUSPENDED','CANCELLED','CONSUMED')),
 revision bigint not null default 1,updated_at timestamptz not null default now(),check(valid_until is null or valid_from is not null and valid_until>valid_from)
);
create index sb_order_delivery_account on cc_internal.sb_order_delivery(account_id);
create table cc_internal.sb_delivery_resources(
 id uuid primary key default gen_random_uuid(),order_id uuid not null references public.cc_portal_stream_orders(id),order_revision bigint not null,
 config_revision bigint not null,secret_id uuid not null references vault.secrets(id),expires_at timestamptz not null,
 source text not null check(source in ('DIRECT','MANUAL','AUTHORIZED_MAIL')),source_message text,created_at timestamptz not null default now()
);
create index sb_delivery_resource_order on cc_internal.sb_delivery_resources(order_id,order_revision,config_revision,expires_at desc);
create table cc_internal.sb_delivery_audit(
 id uuid primary key default gen_random_uuid(),actor_id uuid not null references auth.users(id),order_id uuid references public.cc_portal_stream_orders(id),
 event text not null,status text not null,order_revision bigint,config_revision bigint,created_at timestamptz not null default now()
);
create index sb_delivery_audit_actor_time on cc_internal.sb_delivery_audit(actor_id,created_at desc);
create table cc_internal.sb_delivery_requests(
 id uuid primary key default gen_random_uuid(),order_id uuid not null references public.cc_portal_stream_orders(id),buyer_id uuid not null references auth.users(id),
 seller_id uuid not null references auth.users(id),order_revision bigint not null,status text not null default 'PENDING' check(status in ('PENDING','RESOLVED','SUPERSEDED')),
 created_at timestamptz not null default now(),updated_at timestamptz not null default now(),unique(order_id,order_revision)
);
create index sb_delivery_requests_seller_status on cc_internal.sb_delivery_requests(seller_id,status,created_at desc);
create table cc_internal.sb_delivery_renewals(
 paid_order_id uuid primary key references public.cc_portal_stream_orders(id),root_order_id uuid not null references public.cc_portal_stream_orders(id),created_at timestamptz not null default now(),check(paid_order_id<>root_order_id)
);
-- Privado y no expuesto por PostgREST. Las RPC filtran titular/proveedor y no devuelven secretos de buzones.
do $security$ declare t text;begin
 foreach t in array array['sb_mail_connections','sb_mail_oauth_states','sb_delivery_accounts','sb_order_delivery','sb_delivery_resources','sb_delivery_audit','sb_delivery_requests','sb_delivery_renewals'] loop
  execute format('alter table cc_internal.%I enable row level security',t);
  execute format('revoke all on cc_internal.%I from public,anon,authenticated',t);
  execute format('create policy service_only on cc_internal.%I for all to service_role using (true) with check (true)',t);
 end loop;
end;$security$;

create or replace function cc_internal.sb_delivery_is_seller(p_uid uuid)
returns boolean language sql stable security invoker set search_path='' as $$
 select p_uid is not null and not exists(select 1 from public.cc_admins where user_id=p_uid)
 and exists(select 1 from public.cc_portal_super_resellers r where r.user_id=p_uid and r.enabled)
 and exists(select 1 from public.cc_memberships m join public.cc_businesses b on b.id=m.business_id and b.code='STREAM_BULLS'
 join public.cc_subscriptions s on s.membership_id=m.id join public.cc_plans p on p.id=s.plan_id
 where m.user_id=p_uid and m.status='ACTIVE' and m.role='SUPER_RESELLER' and s.status='ACTIVE' and s.start_at<=now() and s.end_at>now() and p.code='STREAM_365' and p.price_pen>0);
$$;
create or replace function cc_internal.sb_delivery_platform(p_value text)
returns text language sql immutable security invoker set search_path='' as $$
 select case regexp_replace(lower(p_value),'[^a-z0-9]','','g') when 'hbo' then 'max' when 'hbomax' then 'max' when 'disneyplus' then 'disney' when 'chatgptplus' then 'chatgpt' when 'primevideo' then 'prime' when 'amazonprime' then 'prime' else regexp_replace(lower(p_value),'[^a-z0-9]','','g') end;
$$;
create or replace function cc_internal.sb_delivery_new_order()
returns trigger language plpgsql security definer set search_path='' as $$
#variable_conflict use_column
 declare duration integer;begin
 select duration_days into duration from public.cc_portal_stream_products where id=new.product_id;
 insert into cc_internal.sb_order_delivery(order_id,duration_days) values(new.id,greatest(1,least(3650,coalesce(duration,30))));return new;
