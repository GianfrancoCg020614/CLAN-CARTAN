create or replace function cc_internal.sb_delivery_state(p_order uuid,p_buyer uuid)
returns text language plpgsql stable security invoker set search_path='' as $$
#variable_conflict use_column
declare o public.cc_portal_stream_orders%rowtype;d cc_internal.sb_order_delivery%rowtype;a public.sb_oper_accounts%rowtype;
begin
 select * into o from public.cc_portal_stream_orders where id=p_order and buyer_id=p_buyer;
 if not found then return 'DENIED';end if;
 if o.status='REFUNDED' then return 'CANCELLED';end if;
 if o.status='DISPUTED' then return 'SUSPENDED';end if;
 select * into d from cc_internal.sb_order_delivery where order_id=o.id;
 if not found then return 'NOT_READY';end if;
 if d.lifecycle in ('CANCELLED','SUSPENDED','CONSUMED') then return d.lifecycle;end if;
 if d.valid_until<=now() then return 'EXPIRED';end if;
 if d.valid_from>now() then return 'NOT_STARTED';end if;
 if d.lifecycle<>'ACTIVE' or d.valid_from is null or d.valid_until is null or d.account_id is null then return 'NOT_READY';end if;
 select * into a from public.sb_oper_accounts where id=d.account_id and owner_id=o.seller_id;
 if not found or a.state<>'ACTIVE' or a.start_at>now() or a.end_at<=now() then return 'ASSISTANCE_REQUIRED';end if;
 if not exists(select 1 from cc_internal.sb_delivery_accounts c join public.cc_portal_stream_products p on p.id=c.product_id
 where c.account_id=a.id and c.product_id=o.product_id and p.seller_id=o.seller_id and c.commercial_authorized) then return 'NOT_READY';end if;
 return 'ACTIVE';
end;$$;
create or replace function cc_internal.sb_delivery_code_valid(p_code text)
returns boolean language sql immutable security invoker set search_path='' as $$
 select p_code is not null and p_code ~ '^[A-Za-z0-9][A-Za-z0-9 -]{7,127}$' and p_code !~ '^[0-9]{6,8}$';
$$;

create or replace function public.cc_stream_my_order_codes()
returns setof jsonb language sql stable security definer set search_path='' as $$
 select jsonb_build_object('id',o.id,'order_code',o.order_code) from public.cc_portal_stream_orders o
 where (select auth.uid()) is not null and (o.buyer_id=(select auth.uid()) or o.seller_id=(select auth.uid()) or exists(select 1 from public.cc_admins where user_id=(select auth.uid())))
 order by o.created_at desc limit 200;
$$;

create or replace function public.cc_stream_delivery_lookup(p_order_code text)
returns jsonb language plpgsql security definer set search_path='' as $$
#variable_conflict use_column
declare actor uuid:=(select auth.uid());o public.cc_portal_stream_orders%rowtype;d cc_internal.sb_order_delivery%rowtype;
 c cc_internal.sb_delivery_accounts%rowtype;mail cc_internal.sb_mail_connections%rowtype;resource cc_internal.sb_delivery_resources%rowtype;
 state text;request_id uuid;answer jsonb;code text;
begin
 if actor is null then raise exception 'Inicia sesión' using errcode='42501';end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('SB-CODE:'||actor::text,0));
 if (select count(*) from cc_internal.sb_delivery_audit where actor_id=actor and created_at>now()-interval '5 minutes' and event='LOOKUP')>=20 then
  return jsonb_build_object('status','RATE_LIMITED','server_time',now());end if;
 if upper(trim(coalesce(p_order_code,''))) ~ '^ORD-[0-9]{6,15}$' then
  select * into o from public.cc_portal_stream_orders where order_code=upper(trim(p_order_code)) and buyer_id=actor for share;
 end if;
 state:=case when o.id is null then 'DENIED' else cc_internal.sb_delivery_state(o.id,actor) end;
 if state='ASSISTANCE_REQUIRED' then state:='MANUAL';end if;
 if state='ACTIVE' then
  select * into d from cc_internal.sb_order_delivery where order_id=o.id for share;
  select * into c from cc_internal.sb_delivery_accounts where account_id=d.account_id for share;
  perform 1 from public.sb_oper_accounts where id=d.account_id for share;
  state:=cc_internal.sb_delivery_state(o.id,actor);
  if state='ACTIVE' and c.method='AUTOMATIC' then
   select * into mail from cc_internal.sb_mail_connections where id=c.connection_id and owner_id=o.seller_id;
   if mail.status is distinct from 'CONNECTED' or mail.token_secret_id is null then state:='MAIL_DISCONNECTED';end if;
  end if;
  if state='ACTIVE' then
   select * into resource from cc_internal.sb_delivery_resources where order_id=o.id and order_revision=d.revision and config_revision=c.revision and expires_at>now()
    order by created_at desc limit 1;
   if found and c.method in ('DIRECT','MANUAL','AUTOMATIC') then
    select decrypted_secret into code from vault.decrypted_secrets where id=resource.secret_id;
    if cc_internal.sb_delivery_code_valid(code) then state:='AVAILABLE';else state:='NO_CODE';end if;
   else state:=case c.method when 'AUTOMATIC' then 'AUTOMATIC_PENDING' when 'AUTHENTICATOR' then 'AUTHENTICATOR' when 'MANUAL' then 'MANUAL' else 'NO_CODE' end;end if;
  end if;
 end if;
 insert into cc_internal.sb_delivery_audit(actor_id,order_id,event,status,order_revision,config_revision)
 values(actor,o.id,'LOOKUP',state,d.revision,c.revision) returning id into request_id;
 answer:=jsonb_build_object('status',state,'server_time',now());
 if o.id is not null and state<>'DENIED' then answer:=answer||jsonb_build_object('order_code',o.order_code);end if;
 if state='AVAILABLE' then answer:=answer||jsonb_build_object('code',code,'expires_at',least(resource.expires_at,d.valid_until));end if;
 if state='AUTOMATIC_PENDING' then answer:=answer||jsonb_build_object('request_id',request_id);end if;
 return answer;
end;$$;

create or replace function public.cc_stream_delivery_assistance(p_order_code text)
returns jsonb language plpgsql security definer set search_path='' as $$
#variable_conflict use_column
declare actor uuid:=(select auth.uid());o public.cc_portal_stream_orders%rowtype;d cc_internal.sb_order_delivery%rowtype;request_id uuid;
begin
 if actor is null then raise exception 'Inicia sesión' using errcode='42501';end if;
 select * into o from public.cc_portal_stream_orders where order_code=upper(trim(p_order_code)) and buyer_id=actor for share;
 if not found or cc_internal.sb_delivery_state(o.id,actor) not in ('ACTIVE','ASSISTANCE_REQUIRED') then return jsonb_build_object('status','DENIED');end if;
 select * into d from cc_internal.sb_order_delivery where order_id=o.id for share;
 insert into cc_internal.sb_delivery_requests(order_id,buyer_id,seller_id,order_revision) values(o.id,actor,o.seller_id,d.revision)
 on conflict(order_id,order_revision) do update set updated_at=now() returning id into request_id;
 return jsonb_build_object('status','REQUESTED','request_id',request_id);
end;$$;

create or replace function public.cc_stream_delivery_manage(p_action text,p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
#variable_conflict use_column
declare actor uuid:=(select auth.uid());a public.sb_oper_accounts%rowtype;o public.cc_portal_stream_orders%rowtype;renewal public.cc_portal_stream_orders%rowtype;
 d cc_internal.sb_order_delivery%rowtype;c cc_internal.sb_delivery_accounts%rowtype;connection cc_internal.sb_mail_connections%rowtype;
 product public.cc_portal_stream_products%rowtype;sid uuid;code text;until_date timestamptz;is_admin boolean;
begin
 if actor is null then raise exception 'Inicia sesión' using errcode='42501';end if;
 is_admin:=exists(select 1 from public.cc_admins where user_id=actor);
 if p_action='admin_overview' then
  if not is_admin then raise exception 'Solo ADMIN' using errcode='42501';end if;
  return jsonb_build_object('connections',(select coalesce(jsonb_agg(jsonb_build_object('provider',m.provider,'status',m.status,'owner',coalesce(cc.code,'CLAN pendiente'))),'[]') from cc_internal.sb_mail_connections m left join public.cc_clan_codes cc on cc.user_id=m.owner_id),
    'orders',(select coalesce(jsonb_agg(jsonb_build_object('order_code',x.order_code,'service',x.service,'status',x.status,'lifecycle',x.lifecycle,'valid_until',x.valid_until)),'[]') from (select o.order_code,o.service,o.status,d.lifecycle,d.valid_until from public.cc_portal_stream_orders o join cc_internal.sb_order_delivery d on d.order_id=o.id order by o.created_at desc limit 200) x));
 end if;
 if not cc_internal.sb_delivery_is_seller(actor) then raise exception 'Súper reseller con membresía vigente requerido' using errcode='42501';end if;
 if p_action='overview' then
  return jsonb_build_object(
   'accounts',(select coalesce(jsonb_agg(jsonb_build_object('id',a.id,'code',a.code,'service',a.service,'alias',a.alias,'state',a.state,'end_at',a.end_at,'product_id',c.product_id,'method',c.method,'connection_id',c.connection_id,'authorized_sender',c.authorized_sender)),'[]') from public.sb_oper_accounts a left join cc_internal.sb_delivery_accounts c on c.account_id=a.id where a.owner_id=actor),
   'products',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'title',title,'service',service)),'[]') from public.cc_portal_stream_products where seller_id=actor),
   'mailboxes',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'provider',provider,'email_address',email_address,'status',status)),'[]') from cc_internal.sb_mail_connections where owner_id=actor),
   'orders',(select coalesce(jsonb_agg(jsonb_build_object('id',x.id,'order_code',x.order_code,'title',x.title,'service',x.service,'status',x.status,'account_id',x.account_id,'lifecycle',x.lifecycle,'valid_from',x.valid_from,'valid_until',x.valid_until)),'[]') from (select o.id,o.order_code,o.title,o.service,o.status,d.account_id,d.lifecycle,d.valid_from,d.valid_until from public.cc_portal_stream_orders o join cc_internal.sb_order_delivery d on d.order_id=o.id where o.seller_id=actor order by o.created_at desc limit 200) x),
   'requests',(select coalesce(jsonb_agg(jsonb_build_object('id',r.id,'order_code',o.order_code,'service',o.service,'status',r.status,'created_at',r.created_at)),'[]') from cc_internal.sb_delivery_requests r join public.cc_portal_stream_orders o on o.id=r.order_id where r.seller_id=actor and r.status='PENDING')
  );
 end if;
 if p_action='configure_account' then
  select * into a from public.sb_oper_accounts where id=(p_data->>'account_id')::uuid and owner_id=actor for update;
  if not found then raise exception 'Cuenta no autorizada' using errcode='42501';end if;
  select * into product from public.cc_portal_stream_products where id=(p_data->>'product_id')::uuid and seller_id=actor;
  if not found or cc_internal.sb_delivery_platform(a.service)<>cc_internal.sb_delivery_platform(product.service) then raise exception 'La publicación y la cuenta deben ser del mismo proveedor y plataforma';end if;
  if p_data->>'method' not in ('AUTOMATIC','AUTHENTICATOR','MANUAL','DIRECT') or coalesce((p_data->>'commercial_authorized')::boolean,false) is not true then raise exception 'Confirma el uso comercial autorizado; no se admiten factores privados de autenticación';end if;
  if p_data->>'method'='AUTOMATIC' then
   select * into connection from cc_internal.sb_mail_connections where id=(p_data->>'connection_id')::uuid and owner_id=actor and status='CONNECTED';
   if not found or coalesce(p_data->>'authorized_sender','') !~ '^[A-Za-z0-9.!#$%&''*+/=?^_`{|}~-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$' then raise exception 'Conecta un buzón propio y configura el remitente comercial autorizado';end if;
  end if;
  insert into cc_internal.sb_delivery_accounts(account_id,product_id,method,connection_id,authorized_sender,commercial_authorized)
   values(a.id,product.id,p_data->>'method',case when p_data->>'method'='AUTOMATIC' then connection.id else null end,case when p_data->>'method'='AUTOMATIC' then lower(p_data->>'authorized_sender') else null end,true)
  on conflict(account_id) do update set product_id=excluded.product_id,method=excluded.method,connection_id=excluded.connection_id,authorized_sender=excluded.authorized_sender,commercial_authorized=true,revision=cc_internal.sb_delivery_accounts.revision+1,updated_at=now();
  update cc_internal.sb_delivery_requests r set status='SUPERSEDED',updated_at=now() from cc_internal.sb_order_delivery d where r.order_id=d.order_id and d.account_id=a.id and r.status='PENDING';
  return jsonb_build_object('saved',true);
 end if;
 select * into o from public.cc_portal_stream_orders where order_code=upper(trim(p_data->>'order_code')) and seller_id=actor for update;
 if not found then raise exception 'Pedido no autorizado' using errcode='42501';end if;
 select * into d from cc_internal.sb_order_delivery where order_id=o.id for update;
 if p_action='assign_order' then
  if o.status not in ('PAID_AWAITING_DELIVERY','FULFILLED') or d.lifecycle='CONSUMED' then raise exception 'Pedido no habilitado';end if;
  select * into a from public.sb_oper_accounts where id=(p_data->>'account_id')::uuid and owner_id=actor and state='ACTIVE' and start_at<=now() and end_at>now() for update;
  if not found then raise exception 'Cuenta no disponible';end if;
  select * into c from cc_internal.sb_delivery_accounts where account_id=a.id and product_id=o.product_id;
  if not found or cc_internal.sb_delivery_platform(a.service)<>cc_internal.sb_delivery_platform(o.service) then raise exception 'Configura el método de esta cuenta para la publicación del pedido';end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('SB-ASSIGN:'||a.id::text,0));
  if d.account_id is distinct from a.id and (select count(*) from cc_internal.sb_order_delivery x where x.account_id=a.id and x.order_id<>o.id and x.lifecycle='ACTIVE' and x.valid_until>now())>=a.capacity then raise exception 'Cuenta sin disponibilidad';end if;
  update cc_internal.sb_order_delivery set account_id=a.id,valid_from=coalesce(d.valid_from,now()),valid_until=coalesce(d.valid_until,now()+d.duration_days*interval '1 day'),lifecycle=case when d.valid_until<=now() then d.lifecycle else 'ACTIVE' end,revision=revision+1,updated_at=now() where order_id=o.id;
  update cc_internal.sb_delivery_requests set status='SUPERSEDED',updated_at=now() where order_id=o.id and status='PENDING';
  if o.status='PAID_AWAITING_DELIVERY' then perform public.cc_portal_mark_stream_order_delivered(o.id);end if;
 elsif p_action='set_state' then
  if p_data->>'state' not in ('ACTIVE','SUSPENDED','CANCELLED') or d.account_id is null or o.status not in ('PAID_AWAITING_DELIVERY','FULFILLED') then raise exception 'Estado no permitido';end if;
  update cc_internal.sb_order_delivery set lifecycle=p_data->>'state',revision=revision+1,updated_at=now() where order_id=o.id;
 elsif p_action='renew_order' then
  select * into renewal from public.cc_portal_stream_orders where order_code=upper(trim(p_data->>'renewal_order_code')) and seller_id=actor and buyer_id=o.buyer_id and product_id=o.product_id and status in ('PAID_AWAITING_DELIVERY','FULFILLED') for update;
  if not found or renewal.id=o.id or d.account_id is null or o.status not in ('PAID_AWAITING_DELIVERY','FULFILLED') then raise exception 'La renovación requiere otro pedido pagado del mismo comprador y publicación';end if;
  if exists(select 1 from cc_internal.sb_order_delivery where order_id=renewal.id and account_id is not null) then raise exception 'Ese pedido ya tiene una entrega asignada';end if;
  insert into cc_internal.sb_delivery_renewals(paid_order_id,root_order_id) values(renewal.id,o.id);
  update cc_internal.sb_order_delivery set valid_from=case when d.valid_until<=now() then now() else d.valid_from end,valid_until=greatest(now(),d.valid_until)+(select duration_days from cc_internal.sb_order_delivery where order_id=renewal.id)*interval '1 day',lifecycle='ACTIVE',revision=revision+1,updated_at=now() where order_id=o.id;
  update cc_internal.sb_order_delivery set lifecycle='CONSUMED',updated_at=now() where order_id=renewal.id;
 elsif p_action='set_resource' then
  if cc_internal.sb_delivery_state(o.id,o.buyer_id)<>'ACTIVE' then raise exception 'El pedido no está activo';end if;
  select * into c from cc_internal.sb_delivery_accounts where account_id=d.account_id;
  code:=trim(p_data->>'code');
  if c.method not in ('DIRECT','MANUAL') or not cc_internal.sb_delivery_code_valid(code) or coalesce((p_data->>'commercial_authorized')::boolean,false) is not true then raise exception 'Solo licencias y códigos comerciales autorizados; nunca OTP, TOTP, recuperación o doble factor';end if;
  until_date:=least(d.valid_until,coalesce((p_data->>'expires_at')::timestamptz,d.valid_until));
  if until_date<=now() then raise exception 'El código ya venció';end if;
  sid:=vault.create_secret(code);
  insert into cc_internal.sb_delivery_resources(order_id,order_revision,config_revision,secret_id,expires_at,source) values(o.id,d.revision,c.revision,sid,until_date,c.method);
 elsif p_action='resolve_request' then
  update cc_internal.sb_delivery_requests set status='RESOLVED',updated_at=now() where id=(p_data->>'request_id')::uuid and order_id=o.id and seller_id=actor;
  if not found then raise exception 'Solicitud no autorizada';end if;
 else raise exception 'Acción no válida';end if;
 insert into cc_internal.sb_delivery_audit(actor_id,order_id,event,status) values(actor,o.id,p_action,'UPDATED');
 return jsonb_build_object('saved',true);
end;$$;

-- Servicio privado: solamente Edge Functions con service_role; jamás clientes del navegador.
create or replace function public.cc_stream_delivery_service(p_action text,p_data jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
#variable_conflict use_column
declare actor uuid;sid uuid;old_sid uuid;mail cc_internal.sb_mail_connections%rowtype;request cc_internal.sb_delivery_audit%rowtype;
 st cc_internal.sb_mail_oauth_states%rowtype;o public.cc_portal_stream_orders%rowtype;d cc_internal.sb_order_delivery%rowtype;
 c cc_internal.sb_delivery_accounts%rowtype;a public.sb_oper_accounts%rowtype;token_json jsonb;code text;until_date timestamptz;
begin
 if coalesce(auth.jwt()->>'role','')<>'service_role' then raise exception 'Solo servicio' using errcode='42501';end if;
 actor:=nullif(p_data->>'actor_id','')::uuid;
 if p_action='oauth_start' then
  for sid in delete from cc_internal.sb_mail_oauth_states where expires_at<now() returning verifier_secret_id loop delete from vault.secrets where id=sid;end loop;
  if not cc_internal.sb_delivery_is_seller(actor) or p_data->>'provider' not in ('google','microsoft') or length(p_data->>'state_hash')<>64 then raise exception 'Conexión no autorizada' using errcode='42501';end if;
  if (select count(*) from cc_internal.sb_mail_oauth_states where owner_id=actor and created_at>now()-interval '10 minutes')>=10 then raise exception 'Demasiados intentos de conexión';end if;
  sid:=vault.create_secret(p_data->>'verifier');
  insert into cc_internal.sb_mail_oauth_states(state_hash,owner_id,provider,verifier_secret_id,expires_at) values(p_data->>'state_hash',actor,p_data->>'provider',sid,now()+interval '10 minutes');
  return jsonb_build_object('saved',true);
 elsif p_action='oauth_claim' then
  delete from cc_internal.sb_mail_oauth_states where state_hash=p_data->>'state_hash' and provider=p_data->>'provider' returning * into st;
  if not found then raise exception 'Autorización inválida o utilizada';end if;
  select to_jsonb(decrypted_secret) into token_json from vault.decrypted_secrets where id=st.verifier_secret_id;
  delete from vault.secrets where id=st.verifier_secret_id;
  if st.expires_at<=now() or not cc_internal.sb_delivery_is_seller(st.owner_id) then return jsonb_build_object('expired',true);end if;
  return jsonb_build_object('actor_id',st.owner_id,'verifier',token_json);
 elsif p_action='oauth_save' then
  if not cc_internal.sb_delivery_is_seller(actor) or p_data->>'provider' not in ('google','microsoft') or coalesce(p_data->>'email','') !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' or length(coalesce(p_data->>'subject','')) not between 1 and 320 then raise exception 'Conexión no autorizada';end if;
  sid:=vault.create_secret((p_data->'tokens')::text);
  select token_secret_id into old_sid from cc_internal.sb_mail_connections where owner_id=actor and provider=p_data->>'provider' and provider_subject=p_data->>'subject' for update;
  insert into cc_internal.sb_mail_connections(owner_id,provider,provider_subject,email_address,status,token_secret_id)
   values(actor,p_data->>'provider',p_data->>'subject',p_data->>'email','CONNECTED',sid)
  on conflict(owner_id,provider,provider_subject) do update set email_address=excluded.email_address,status='CONNECTED',token_secret_id=excluded.token_secret_id,updated_at=now();
  if old_sid is not null then delete from vault.secrets where id=old_sid;end if;
  return jsonb_build_object('saved',true);
 elsif p_action in ('mail_disconnect','mail_for_disconnect') then
  select * into mail from cc_internal.sb_mail_connections where id=(p_data->>'connection_id')::uuid and owner_id=actor for update;
  if not found or not cc_internal.sb_delivery_is_seller(actor) then raise exception 'Buzón no autorizado' using errcode='42501';end if;
  if p_action='mail_for_disconnect' then
   select decrypted_secret::jsonb into token_json from vault.decrypted_secrets where id=mail.token_secret_id;
   return jsonb_build_object('provider',mail.provider,'tokens',token_json);
  end if;
  update cc_internal.sb_mail_connections set status='DISCONNECTED',token_secret_id=null,updated_at=now() where id=mail.id;
  if mail.token_secret_id is not null then delete from vault.secrets where id=mail.token_secret_id;end if;
  return jsonb_build_object('saved',true);
 end if;
 select * into request from cc_internal.sb_delivery_audit where id=(p_data->>'request_id')::uuid and actor_id=actor and event='LOOKUP' and status='AUTOMATIC_PENDING' and created_at>now()-interval '2 minutes' for update;
 if not found or cc_internal.sb_delivery_state(request.order_id,actor)<>'ACTIVE' then return jsonb_build_object('status','DENIED');end if;
 select * into o from public.cc_portal_stream_orders where id=request.order_id;
 select * into d from cc_internal.sb_order_delivery where order_id=o.id for share;
 select * into c from cc_internal.sb_delivery_accounts where account_id=d.account_id for share;
 perform 1 from public.sb_oper_accounts where id=d.account_id for share;
 if cc_internal.sb_delivery_state(o.id,actor)<>'ACTIVE' then return jsonb_build_object('status','DENIED');end if;
 if request.order_revision<>d.revision or request.config_revision<>c.revision or c.method<>'AUTOMATIC' then return jsonb_build_object('status','DENIED');end if;
 select * into mail from cc_internal.sb_mail_connections where id=c.connection_id and owner_id=o.seller_id for share;
 if mail.status is distinct from 'CONNECTED' or mail.token_secret_id is null then return jsonb_build_object('status','MAIL_DISCONNECTED');end if;
 if p_action='mail_context' then
  select * into a from public.sb_oper_accounts where id=d.account_id;
  select decrypted_secret::jsonb into token_json from vault.decrypted_secrets where id=mail.token_secret_id;
  return jsonb_build_object('status','READY','order_code',o.order_code,'account_code',a.code,'provider',mail.provider,'connection_id',mail.id,'authorized_sender',c.authorized_sender,'tokens',token_json,'valid_from',d.valid_from,'valid_until',d.valid_until);
 elsif p_action='mail_tokens' then
  -- FOR UPDATE evita reinsertar tokens tras desconectar el buzón en otra transacción.
  select * into mail from cc_internal.sb_mail_connections where id=mail.id and status='CONNECTED' for update;
  if not found then return jsonb_build_object('status','MAIL_DISCONNECTED');end if;
  perform vault.update_secret(mail.token_secret_id,(p_data->'tokens')::text);
  return jsonb_build_object('saved',true);
 elsif p_action='mail_reauth' then
  update cc_internal.sb_mail_connections set status='REAUTH_REQUIRED',updated_at=now() where id=mail.id;
  return jsonb_build_object('status','MAIL_DISCONNECTED');
 elsif p_action='complete' then
  code:=p_data->>'code';until_date:=least((p_data->>'expires_at')::timestamptz,d.valid_until);
  if not cc_internal.sb_delivery_code_valid(code) or until_date<=now() or until_date>now()+interval '15 minutes' then raise exception 'Entrega comercial inválida';end if;
  sid:=vault.create_secret(code);
  insert into cc_internal.sb_delivery_resources(order_id,order_revision,config_revision,secret_id,expires_at,source,source_message) values(o.id,d.revision,c.revision,sid,until_date,'AUTHORIZED_MAIL',left(p_data->>'message_id',250));
  update cc_internal.sb_delivery_audit set status='AVAILABLE' where id=request.id;
  return jsonb_build_object('status','AVAILABLE','order_code',o.order_code,'code',code,'expires_at',until_date,'server_time',now());
 elsif p_action='no_code' then
  update cc_internal.sb_delivery_audit set status='NO_CODE' where id=request.id;
  return jsonb_build_object('status','NO_CODE','order_code',o.order_code,'server_time',now());
 end if;
 raise exception 'Acción de servicio inválida';
end;$$;

