-- V174: registro CLAN permanente. Aplicado primero en producción mediante migración segura.
-- No sustituye la autenticación ni concede roles o membresías.
create table if not exists public.cc_portal_user_registry (
 user_id uuid primary key references auth.users(id) on delete cascade,
 registry_no bigint generated by default as identity unique not null,
 display_alias text,
 registered_at timestamptz not null default now(),
 recorded_at timestamptz not null default now(),
 constraint cc_portal_user_registry_alias_check
 check (display_alias is null or length(btrim(display_alias)) between 2 and 80)
);
alter table public.cc_portal_user_registry enable row level security;
revoke all on table public.cc_portal_user_registry from public,anon,authenticated;
revoke all on sequence public.cc_portal_user_registry_registry_no_seq from public,anon,authenticated;

insert into public.cc_portal_user_registry(user_id,registered_at,display_alias)
select u.id,u.created_at,case row_number() over(order by u.created_at,u.id)
 when 1 then 'CLAN1' when 2 then 'CLAN CARTAN' when 3 then 'LUIS CAR' else null end
from auth.users u order by u.created_at,u.id
on conflict(user_id) do nothing;

create or replace function public.cc_portal_admin_accounts_v2()
returns setof jsonb language plpgsql volatile security definer set search_path=''
as $fn$
begin
 if (select auth.uid()) is null or not exists
 (select 1 from public.cc_admins where user_id=(select auth.uid()))
 then raise exception 'Solo ADMIN puede consultar el registro' using errcode='42501'; end if;
 insert into public.cc_portal_user_registry(user_id,registered_at)
 select u.id,u.created_at from auth.users u
 where not exists(select 1 from public.cc_portal_user_registry r where r.user_id=u.id)
 order by u.created_at,u.id on conflict(user_id) do nothing;
 return query
 select to_jsonb(a)||jsonb_build_object(
 'registry_no',r.registry_no,
 'registry_code','CLAN'||r.registry_no::text,
 'registry_alias',coalesce(nullif(r.display_alias,''),nullif(a.display_name,''),split_part(a.email,'@',1)),
 'registered_at',r.registered_at)
 from public.cc_portal_admin_accounts() a
 join auth.users u on lower(u.email)=lower(a.email)
 join public.cc_portal_user_registry r on r.user_id=u.id
 order by r.registry_no limit 250;
end;
$fn$;
revoke all on function public.cc_portal_admin_accounts_v2() from public,anon;
grant execute on function public.cc_portal_admin_accounts_v2() to authenticated;

create or replace function public.cc_portal_admin_set_registry_alias(p_registry_no bigint,p_alias text)
returns boolean language plpgsql volatile security definer set search_path=''
as $fn$
begin
 if (select auth.uid()) is null or not exists
 (select 1 from public.cc_admins where user_id=(select auth.uid()))
 then raise exception 'Solo ADMIN puede editar alias' using errcode='42501'; end if;
 if p_registry_no is null or p_alias is null or length(btrim(p_alias)) not between 2 and 80
 then raise exception 'Alias inválido' using errcode='22023'; end if;
 update public.cc_portal_user_registry set display_alias=btrim(p_alias)
 where registry_no=p_registry_no;
 return found;
end;
$fn$;
revoke all on function public.cc_portal_admin_set_registry_alias(bigint,text) from public,anon;
grant execute on function public.cc_portal_admin_set_registry_alias(bigint,text) to authenticated;
