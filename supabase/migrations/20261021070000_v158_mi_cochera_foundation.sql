-- Las RPC siguientes administran escrituras; ningun reseller puede alterar saldos directamente.
create or replace function public.mc_ensure_account()
returns table(invite_code text,currency text,subscription_until timestamptz,bonus_pen numeric,suspended boolean)
language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid();
begin
 if u is null then raise exception 'Inicia sesion'; end if;
 insert into public.mc_accounts(user_id) values(u) on conflict(user_id) do nothing;
 return query select a.invite_code,a.currency,a.subscription_until,a.bonus_pen,a.suspended from public.mc_accounts a where a.user_id=u;
end $$;
create or replace function public.mc_admin_grant_bonus(p_reseller uuid,p_amount numeric,p_request uuid,p_note text default 'Bono gratuito ADMIN')
returns numeric language plpgsql security definer set search_path='' as $$
declare current_amount numeric;
begin
 if auth.uid() is null or not exists(select 1 from public.cc_admins a where a.user_id=auth.uid()) then raise exception 'Solo ADMIN';end if;
 if p_reseller is null or p_request is null or p_amount is null or p_amount<=0 or p_amount>10000 or p_amount<>round(p_amount,2) then raise exception 'Importe o referencia incorrectos';end if;
 if not exists(select 1 from auth.users where id=p_reseller) then raise exception 'Usuario inexistente';end if;
 insert into public.mc_accounts(user_id) values(p_reseller) on conflict(user_id) do nothing;
 select bonus_pen into current_amount from public.mc_accounts where user_id=p_reseller for update;
 if exists(select 1 from public.mc_bonus_events where request_id=p_request) then
  if not exists(select 1 from public.mc_bonus_events where request_id=p_request and reseller_id=p_reseller and amount_pen=p_amount and kind='ADMIN_GRANT') then raise exception 'Referencia reutilizada';end if;
  return current_amount;
 end if;
 update public.mc_accounts set bonus_pen=bonus_pen+p_amount where user_id=p_reseller returning bonus_pen into current_amount;
 insert into public.mc_bonus_events(request_id,reseller_id,actor_id,amount_pen,kind,note)
 values(p_request,p_reseller,auth.uid(),p_amount,'ADMIN_GRANT',left(coalesce(p_note,''),250));
 return current_amount;
end $$;
create or replace function public.mc_activate_with_bonus(p_request uuid)
returns timestamptz language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid();a public.mc_accounts%rowtype; until_date timestamptz;
begin
 if u is null or p_request is null then raise exception 'No autorizado';end if;
 perform public.mc_ensure_account();
 select * into a from public.mc_accounts where user_id=u for update;
 if exists(select 1 from public.mc_subscription_events where request_id=p_request) then
  if not exists(select 1 from public.mc_subscription_events where request_id=p_request and reseller_id=u and paid_with='BONUS') then raise exception 'Referencia reutilizada';end if;
  return a.subscription_until;
 end if;
 if a.suspended then raise exception 'Cuenta suspendida';end if;
 if a.bonus_pen<15 then raise exception 'Bono insuficiente';end if;
 until_date:=greatest(now(),coalesce(a.subscription_until,now()))+interval '30 days';
 update public.mc_accounts set bonus_pen=bonus_pen-15,subscription_until=until_date where user_id=u;
 insert into public.mc_bonus_events(request_id,reseller_id,actor_id,amount_pen,kind,note) values(p_request,u,u,-15,'MONTHLY_SPEND','30 dias MI COCHERA');
 insert into public.mc_subscription_events(request_id,reseller_id,paid_with,amount_pen,active_until) values(p_request,u,'BONUS',15,until_date);
 return until_date;
end $$;
create or replace function public.mc_create_cart(p_alias text,p_type text,p_rate numeric,p_owner_kind text,p_owner_doc text,p_owner_name text,p_owner_phone text,p_worker_kind text default null,p_worker_doc text default null,p_worker_name text default null,p_worker_phone text default null)
returns bigint language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid(); a public.mc_accounts%rowtype; oid uuid; wid uuid;cid bigint;
begin
 select * into a from public.mc_accounts where user_id=u;
 if u is null or a.user_id is null or a.suspended or a.subscription_until<=now() or a.subscription_until is null then raise exception 'MI COCHERA no esta activa';end if;
 if p_rate is null or p_rate<=0 or p_rate>100000 or p_rate<>round(p_rate,2) then raise exception 'Tarifa incorrecta';end if;
 if length(trim(coalesce(p_owner_name,'')))<2 or length(trim(coalesce(p_owner_doc,'')))<4 or length(trim(coalesce(p_type,'')))<2 then raise exception 'Datos obligatorios incompletos';end if;
 if p_owner_kind not in ('DNI','CE','PASSPORT','CEDULA','OTHER') then raise exception 'Documento invalido';end if;
 insert into public.mc_people(reseller_id,document_type,document_number,full_name,phone)
 values(u,p_owner_kind,left(trim(p_owner_doc),40),left(trim(p_owner_name),160),left(trim(coalesce(p_owner_phone,'')),30))
 on conflict(reseller_id,document_type,document_number) do update set
 full_name=case when public.mc_people.verification_source='API_PERU' then public.mc_people.full_name else excluded.full_name end,
 phone=excluded.phone returning id into oid;
 if nullif(trim(coalesce(p_worker_doc,'')),'') is not null then
  if p_worker_kind not in ('DNI','CE','PASSPORT','CEDULA','OTHER') or length(trim(coalesce(p_worker_name,'')))<2 then raise exception 'Trabajador incompleto';end if;
  insert into public.mc_people(reseller_id,document_type,document_number,full_name,phone)
  values(u,p_worker_kind,left(trim(p_worker_doc),40),left(trim(p_worker_name),160),left(trim(coalesce(p_worker_phone,'')),30))
  on conflict(reseller_id,document_type,document_number) do update set
  full_name=case when public.mc_people.verification_source='API_PERU' then public.mc_people.full_name else excluded.full_name end,
  phone=excluded.phone returning id into wid;
 end if;
 insert into public.mc_carts(reseller_id,alias,business_type,owner_person_id,worker_person_id,daily_rate,currency)
 values(u,left(trim(coalesce(p_alias,'')),80),left(trim(p_type),100),oid,wid,p_rate,a.currency) returning id into cid;
 insert into public.mc_stays(cart_id,reseller_id) values(cid,u);
 return cid;
end $$;
create or replace function public.mc_sync_rents()
returns integer language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid();n integer;
begin
 if u is null or not exists(select 1 from public.mc_accounts where user_id=u and not suspended and subscription_until>now()) then raise exception 'MI COCHERA no esta activa';end if;
 insert into public.mc_movements(cart_id,reseller_id,stay_id,kind,label,amount_local,currency,occurred_on)
 select c.id,u,s.id,'RENT','Alquiler diario',c.daily_rate,c.currency,g::date
 from public.mc_stays s join public.mc_carts c on c.id=s.cart_id and c.reseller_id=u
 cross join lateral generate_series(s.joined_on,least(coalesce(s.left_on,(timezone('America/Lima',now()))::date),(timezone('America/Lima',now()))::date),interval '1 day') g
 where s.reseller_id=u and s.joined_on>(timezone('America/Lima',now()))::date-interval '3650 days'
 on conflict do nothing;
 get diagnostics n=row_count;return n;
end $$;
create or replace function public.mc_record_movement(p_cart bigint,p_kind text,p_label text,p_quantity numeric,p_unit numeric,p_amount numeric,p_method text default null)
returns uuid language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid();c public.mc_carts%rowtype;mid uuid; debt numeric;
begin
 if u is null or not exists(select 1 from public.mc_accounts where user_id=u and not suspended and subscription_until>now()) then raise exception 'MI COCHERA no esta activa';end if;
 select * into c from public.mc_carts where id=p_cart and reseller_id=u for update;
 if c.id is null then raise exception 'Carrito inexistente';end if;
 if p_kind='PRODUCT' then
  if c.state<>'ACTIVE' or p_quantity is null or p_quantity<=0 or p_unit is null or p_unit<=0 or p_amount<>round(p_quantity*p_unit,2) or p_amount>100000 then raise exception 'Venta incorrecta';end if;
 elsif p_kind='PAYMENT' then
  if p_amount is null or p_amount>=0 or p_amount<>round(p_amount,2) then raise exception 'Pago incorrecto';end if;
  perform public.mc_sync_rents();
  select coalesce(sum(amount_local),0) into debt from public.mc_movements where cart_id=p_cart and reseller_id=u;
  if -p_amount>debt then raise exception 'El pago supera la deuda';end if;
 else raise exception 'Movimiento no admitido';end if;
 insert into public.mc_movements(cart_id,reseller_id,kind,label,quantity,unit_price,amount_local,currency,payment_method)
 values(p_cart,u,p_kind,left(trim(p_label),120),p_quantity,p_unit,p_amount,c.currency,case when p_kind='PAYMENT' then left(coalesce(p_method,''),40) else null end) returning id into mid;
 return mid;
end $$;
create or replace function public.mc_change_cart_state(p_cart bigint,p_new_state text)
returns void language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid(); old_state text;today_pe date:=(timezone('America/Lima',now()))::date;
begin
 if u is null or not exists(select 1 from public.mc_accounts where user_id=u and not suspended and subscription_until>now()) then raise exception 'MI COCHERA no esta activa';end if;
 if p_new_state not in ('ACTIVE','RETIRED') then raise exception 'Estado invalido';end if;
 select state into old_state from public.mc_carts where id=p_cart and reseller_id=u for update;
 if old_state is null then raise exception 'Carrito inexistente';end if;
 if old_state=p_new_state then return;end if;
 if p_new_state='RETIRED' then
  perform public.mc_sync_rents();
  update public.mc_stays set left_on=today_pe where cart_id=p_cart and reseller_id=u and left_on is null;
 else
  insert into public.mc_stays(cart_id,reseller_id,joined_on) values(p_cart,u,today_pe);
 end if;
 update public.mc_carts set state=p_new_state where id=p_cart and reseller_id=u;
end $$;
