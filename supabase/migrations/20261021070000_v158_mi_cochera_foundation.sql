-- V158 MI COCHERA · Extension aditiva; sin habilitar cobros externos.
-- Puntos clave: identidad Supabase compartida, datos aislados por RESELLER, bono promocional intransferible.
create sequence if not exists public.mc_invitation_seq start 1;
create table if not exists public.mc_accounts(
 user_id uuid primary key references auth.users(id) on delete cascade,
 invite_code text not null unique default ('COCHERA'||nextval('public.mc_invitation_seq')::text),
 country char(2) not null default 'PE',
 currency text not null default 'PEN' check(currency in ('PEN','USD','EUR','COP','MXN','ARS','CLP','BOB','BRL','UYU','PYG','CRC','DOP','CAD','GBP')),
 subscription_until timestamptz,
 suspended boolean not null default false,
 bonus_pen numeric(12,2) not null default 0 check(bonus_pen>=0),
 created_at timestamptz not null default now()
);
create table if not exists public.mc_people(
 id uuid primary key default gen_random_uuid(),
 reseller_id uuid not null references auth.users(id),
 country char(2) not null default 'PE',
 document_type text not null check(document_type in ('DNI','CE','PASSPORT','CEDULA','OTHER')),
 document_number text not null,
 full_name text not null check(length(trim(full_name)) between 2 and 160),
 phone text,
 verification_source text not null default 'MANUAL' check(verification_source in ('MANUAL','API_PERU')),
 created_at timestamptz not null default now(),
 unique(reseller_id,document_type,document_number),
 unique(id,reseller_id)
);
create table if not exists public.mc_carts(
 id bigint generated by default as identity primary key,
 reseller_id uuid not null references auth.users(id),
 alias text not null default '',
 business_type text not null,
 owner_person_id uuid not null,
 worker_person_id uuid,
 daily_rate numeric(12,2) not null check(daily_rate>0),
 currency text not null,
 state text not null default 'ACTIVE' check(state in ('ACTIVE','RETIRED')),
 created_at timestamptz not null default now(),
 unique(id,reseller_id),
 foreign key(owner_person_id,reseller_id) references public.mc_people(id,reseller_id),
 foreign key(worker_person_id,reseller_id) references public.mc_people(id,reseller_id)
);
create table if not exists public.mc_stays(
 id uuid primary key default gen_random_uuid(),
 cart_id bigint not null,
 reseller_id uuid not null references auth.users(id),
 joined_on date not null default (timezone('America/Lima',now()))::date,
 left_on date,
 created_at timestamptz not null default now(),
 foreign key(cart_id,reseller_id) references public.mc_carts(id,reseller_id),
 check(left_on is null or left_on>=joined_on)
);
create unique index if not exists mc_stays_one_active on public.mc_stays(cart_id) where left_on is null;
create table if not exists public.mc_movements(
 id uuid primary key default gen_random_uuid(),
 cart_id bigint not null,
 reseller_id uuid not null references auth.users(id),
 stay_id uuid references public.mc_stays(id),
 kind text not null check(kind in ('RENT','PRODUCT','PAYMENT')),
 label text not null,
 quantity numeric(12,3),
 unit_price numeric(12,2),
 amount_local numeric(12,2) not null check(amount_local<>0),
 currency text not null,
 occurred_on date not null default (timezone('America/Lima',now()))::date,
 payment_method text,
 created_at timestamptz not null default now(),
 foreign key(cart_id,reseller_id) references public.mc_carts(id,reseller_id),
 check((kind='PAYMENT' and amount_local<0) or (kind<>'PAYMENT' and amount_local>0))
);
create unique index if not exists mc_one_rent_per_stay_day on public.mc_movements(stay_id,occurred_on) where kind='RENT';
create index if not exists mc_movements_tenant_cart on public.mc_movements(reseller_id,cart_id,occurred_on);
create table if not exists public.mc_bonus_events(
 id uuid primary key default gen_random_uuid(),
 request_id uuid not null unique,
 reseller_id uuid not null references auth.users(id),
 actor_id uuid not null references auth.users(id),
 amount_pen numeric(12,2) not null check(amount_pen<>0),
 kind text not null check(kind in ('ADMIN_GRANT','MONTHLY_SPEND')),
 note text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.mc_subscription_events(
 id uuid primary key default gen_random_uuid(),
 request_id uuid not null unique,
 reseller_id uuid not null references auth.users(id),
 paid_with text not null check(paid_with in ('BONUS','VERIFIED_REAL')),
 amount_pen numeric(12,2) not null check(amount_pen=15),
 active_until timestamptz not null,
 created_at timestamptz not null default now()
);
create table if not exists public.mc_recharge_intents(
 id uuid primary key default gen_random_uuid(),
 reseller_id uuid not null references auth.users(id),
 provider text not null check(provider in ('LEMON_DALE','BINANCE_USDT')),
 mode text not null check(mode in ('MANUAL','AUTOMATICA')),
 operation_reference text not null,
 declared_amount numeric(14,6) not null check(declared_amount>0),
 declared_currency text not null check(declared_currency in ('PEN','USDT')),
 status text not null default 'PENDING' check(status in ('PENDING','REJECTED','VERIFIED','CREDITED')),
 created_at timestamptz not null default now(),
 unique(provider,operation_reference)
);
