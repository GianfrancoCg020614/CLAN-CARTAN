import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const checks=[];
const verify=(name,condition)=>checks.push([name,Boolean(condition)]);
const auth=read('supabase/functions/ma-verify-dni/index.ts');
const portal=read('scripts/v161-1-mi-alquiler.js');
const cardCss=read('styles/v161-1-mi-alquiler.css');
const svg=read('assets/mi-alquiler-logo.svg');
const captcha=read('scripts/v123-turnstile.js');
const wa=read('scripts/v161-4-mi-alquiler.js');
const wallet=read('scripts/v162-1-mi-alquiler-wallets.js');
const template=read('supabase/templates/confirm-signup-recovery-v162-1.html');
const flow=read('.github/workflows/validar-portal.yml');
const status=JSON.parse(read('docs/V163-5-ESTADO.json'));
const suite=JSON.parse(read('docs/matriz-e2e-v163-4.json'));
verify('El logo oficial está en tarjeta y panel',(portal.match(/assets\/mi-alquiler-logo\.svg/g)||[]).length===2);
verify('Logo embebido en SVG',svg.includes('data:image/webp;base64,'));
const b64=svg.match(/data:image\/webp;base64,([A-Za-z0-9+/=]+)/)?.[1]||'';
const binary=Buffer.from(b64,'base64');
verify('Logo WebP válido',binary.length>1000&&binary.toString('ascii',0,4)==='RIFF'&&binary.toString('ascii',8,12)==='WEBP');
verify('Logo responsive',cardCss.includes('ma1611-brand-logo')&&cardCss.includes('@media'));
verify('Cuarta tarjeta',portal.includes("card.id = 'ma1611card'"));
verify('Sesión compartida',portal.includes('session()?.jwt'));
verify('Login original preservado',portal.includes('window.cc77Auth(false)'));
verify('DNI usa API Perú .dev',auth.includes('https://api.apiperu.dev/dni'));
verify('DNI endpoint .pe retirado',!auth.includes('https://api.apiperu.pe/dni'));
verify('DNI token secreto backend',auth.includes('APIPERU_TOKEN'));
verify('DNI JWT servidor',auth.includes('/auth/v1/user'));
verify('DNI membresía',auth.includes('subscription_until')&&auth.includes('suspended'));
verify('DNI autorización central',auth.includes('cc_dni_auto_permission'));
verify('DNI cuota compartida',auth.includes('cc_claim_dni_quota'));
verify('DNI autorización antes del gasto de cuota',auth.indexOf('cc_dni_auto_permission')<auth.indexOf('cc_claim_dni_quota'));
verify('DNI valida número recibido',auth.includes('response_mismatch'));
verify('DNI no edita cartera',!/(ma_tenants.*(PATCH|DELETE|POST))/.test(auth));
verify('DNI timeout',auth.includes('AbortController'));
verify('Plantilla OTP dinámica',template.includes('{{ .Token }}'));
verify('Plantilla OTP sin JavaScript',!/<script\b/i.test(template));
verify('Turnstile obtiene token',captcha.includes('window.cc123CaptchaToken'));
verify('Turnstile puede resetear',captcha.includes('window.cc123ResetCaptcha'));
verify('Turnstile desactivado hasta configurar sitio',captcha.includes('if(!sitekey)return;'));
verify('Turnstile fallos no autentican',captcha.includes("'error-callback'"));
verify('WhatsApp requiere consentimiento',wa.includes('consent_whatsapp===true')&&wa.includes('a.permit&&a.tel'));
verify('WhatsApp apertura voluntaria',wa.includes('https://wa.me/')&&wa.includes('noopener noreferrer'));
verify('WhatsApp se registra como apertura',wa.includes('ma_log_notice')&&wa.includes('data-ma4-notice'));
verify('WhatsApp no presume entrega',wa.includes('no confirma entrega'));
verify('Cuatro billeteras',wallet.includes('Mis cuatro billeteras')&&wallet.includes('MI_ALQUILER'));
verify('Recargas sólo pendientes',wallet.includes('PENDIENTE')&&wallet.includes('verificad'));
verify('Pruebas E2E declaradas',suite.length===24&&suite.every((x,i)=>x.id==='E2E-'+String(i+1).padStart(2,'0')));
verify('E2E pendientes explícitas',suite.every(x=>x.estado==='No ejecutada'));
verify('Auditoría SQL compatible V163.2',fs.existsSync('scripts/auditoria-v163-2-supabase.sql'));
verify('Auditoría SQL de seguridad V163.4',fs.existsSync('scripts/auditoria-v163-4.sql'));
verify('CI comprueba V163.5',flow.includes('node scripts/check-v163-5-integracion.mjs'));
verify('CI bloquea publicación',flow.includes('node scripts/check-v163-5-prepublicacion.mjs'));
verify('Pagos automáticos inactivos',status.controls.real_payments_enabled===false);
verify('WhatsApp automático inactivo',status.controls.automatic_whatsapp_send_enabled===false);
verify('Turnstile no activado',status.controls.turnstile_auth_enabled===false);
verify('Fusión de producción no aprobada',status.controls.production_merge_approved===false);
verify('Migración experimental no incorporada',!fs.existsSync('supabase/migrations/20261021123000_v163_mi_alquiler.sql'));
for(const [name,ok] of checks)console.log((ok?'PASS':'FAIL')+' '+name);
const failures=checks.filter(([,ok])=>!ok);
console.log('V163.5: '+(checks.length-failures.length)+'/'+checks.length+' comprobaciones estáticas.');
if(failures.length)process.exitCode=1;