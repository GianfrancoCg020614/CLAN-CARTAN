import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import fs from 'node:fs';
const vars=Object.fromEntries(fs.readFileSync('.parte1-local/status.env','utf8').split('\n').map(s=>s.trim()).filter(s=>/^[A-Z][A-Z_0-9]*=/.test(s)).map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1).replace(/^"|"$/g,'')]}));
const api=vars.API_URL||vars.SUPABASE_URL||'http://127.0.0.1:54321';
const key=vars.ANON_KEY||vars.SUPABASE_ANON_KEY;
assert.ok(key,'Se requiere clave pública de Supabase LOCAL');
assert.ok(api.includes('127.0.0.1')||api.includes('localhost'),'Nunca conectar pruebas a producción');
const headers={'apikey':key,'Content-Type':'application/json'};
const call=async(path,body)=>{const r=await fetch(api+path,{method:'POST',headers,body:JSON.stringify(body)});let data={};try{data=await r.json()}catch{}return {status:r.status,ok:r.ok,data}};
const stamp=randomUUID().replace(/-/g,'').slice(0,16);
const password='PruebaAislada2026!Segura';
const bad=await call('/auth/v1/signup',{email:'sin-consent-'+stamp+'@example.test',password,data:{full_name:'Persona De Prueba'}});
assert.equal(bad.ok,false,'Debe bloquear signup sin declaración legal');
console.log('PASS: signup sin consentimiento denegado ('+bad.status+').');
const email='con-consent-'+stamp+'@example.test';
const accepted={full_name:'Persona De Prueba',legal_accepted:true,data_processing_accepted:true,
  terms_version:'V161-20261021',privacy_version:'V161-20261021',
  data_processing_version:'V164-20261023',marketing_consent:false};
const ok=await call('/auth/v1/signup',{email,password,data:accepted});
assert.equal(ok.ok,true,'Alta local con consentimientos falló: '+JSON.stringify(ok.data));
assert.ok(ok.data.user?.id,'Debe existir usuario local');
console.log('PASS: signup con privacidad aprobada y marketing no aprobado.');
const signin=await call('/auth/v1/token?grant_type=password',{email,password});
assert.equal(signin.ok,true,'Login local falló: '+JSON.stringify(signin.data));
assert.ok(signin.data.access_token,'No llegó el access_token');
console.log('PASS: login real LOCAL confirmado.');
const legalUrl=api+'/rest/v1/cc_part1_legal_consents?select=user_id,terms_version,privacy_version,data_processing_version&user_id=eq.'+encodeURIComponent(ok.data.user.id);
const recorded=await fetch(legalUrl,{headers:{apikey:key,Authorization:'Bearer '+signin.data.access_token}});
assert.equal(recorded.ok,true,'Usuario autenticado debe poder leer su propia auditoría: '+recorded.status);
const rows=await recorded.json();
assert.equal(rows.length,1,'Debe quedar exactamente una declaración por alta');
assert.equal(rows[0].terms_version,'V161-20261021');
assert.equal(rows[0].privacy_version,'V161-20261021');
assert.equal(rows[0].data_processing_version,'V164-20261023');
console.log('PASS: auditoría legal guardada y visible para su propio usuario.');
const forbidden=await fetch(legalUrl,{headers:{apikey:key}});
const publicRows=forbidden.ok?await forbidden.json():[];
assert.equal(publicRows.length,0,'El consentimiento legal no debe estar disponible anónimamente');
console.log('PASS: la declaración de privacidad no se expone al público.');
const wrong=await call('/auth/v1/token?grant_type=password',{email,password:'Incorrecta2026!'});
assert.equal(wrong.ok,false,'Password inválida no debería dar acceso');
console.log('PASS: credenciales incorrectas rechazadas.');
const recovery=await call('/auth/v1/recover',{email});
assert.equal(recovery.ok,true,'Recuperación local no aceptada: '+JSON.stringify(recovery.data));
console.log('PASS: recuperación de acceso local aceptada.');
const yes=await call('/auth/v1/signup',{email:'con-marketing-'+stamp+'@example.test',password,data:{...accepted,marketing_consent:true}});
assert.equal(yes.ok,true,'Marketing permitido no debe bloquear registro');
console.log('PASS: marketing marcado voluntariamente.');
const noPrivacy=await call('/auth/v1/signup',{email:'sin-privacidad-'+stamp+'@example.test',password,data:{...accepted,data_processing_accepted:false,marketing_consent:true}});
assert.equal(noPrivacy.ok,false,'Marketing no sustituye aceptación de privacidad');
console.log('PASS: publicidad no permite saltarse privacidad.');
console.log('PASS: 7 escenarios con Supabase Auth LOCAL aislado de producción.');